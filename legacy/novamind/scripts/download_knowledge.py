# Gera arquivos de texto por dominio
total_facts = 0
for domain, facts in DOMAIN_SEEDS.items():
    filepath = os.path.join(OUTPUT_DIR, f"{domain}.txt")
    with open(filepath, "w", encoding="utf-8") as f:
        for fact in facts:
            f.write(fact + "\n")
    total_facts += len(facts)
    print(f"  {domain}: {len(facts)} fatos → {filepath}")

# Salva metadados combinados
combined_path = os.path.join(OUTPUT_DIR, "_manifest.json")
with open(combined_path, "w", encoding="utf-8") as f:
    json.dump({
        "domains": list(DOMAIN_SEEDS.keys()),
        "total_domains": len(DOMAIN_SEEDS),
        "total_facts": total_facts,
        "paths": {d: f"{d}.txt" for d in DOMAIN_SEEDS},
    }, f, indent=2)

print(f"\nTotal: {total_facts} fatos em {len(DOMAIN_SEEDS)} dominios")
print(f"Manifesto: {combined_path}")

