"""
run_massive_inference.py — Roda 1M+ inferencias e gera relatorio de descobertas NOVAS.
"""
import sys, os, json, time
sys.path.insert(0, os.path.dirname(__file__))

REPORT_PATH = r"D:\novamind_data\agi_novel_discoveries.md"

# Load everything
from core.knowledge_graph import KnowledgeGraph
from core.inference_engine import InferenceEngine

kg = KnowledgeGraph()
print("Carregando KnowledgeGraph...")
with open(r"D:\novamind_data\knowledge_graph\concepts.json", encoding="utf-8") as f:
    data = json.load(f)
for name, info in data.items():
    kg.add_concept(name, domain=info.get("domain", ""))
print(f"  {len(kg.concepts)} conceitos")

with open(r"D:\novamind_data\knowledge_graph\relations.json", encoding="utf-8") as f:
    rels = json.load(f)
for r in rels:
    kg.add_causal_relation(
        r.get("source", ""), r.get("target", ""),
        r.get("type", ""), confidence=r.get("confidence", 0.5),
        evidence=r.get("evidence", ""), domain=r.get("domain", ""),
    )
print(f"  {kg.total_relations} relacoes")

# Run inference engine
engine = InferenceEngine(kg)
all_novel = engine.run_all(target_diseases=[
    "Alzheimer", "Parkinson", "ALS", "Huntington",
    "multiple sclerosis", "schizophrenia", "depression",
    "autism", "bipolar", "cancer", "diabetes",
    "stroke", "HIV", "epilepsy", "cirrhosis",
    "kidney disease", "lung disease", "osteoporosis",
])

# Stats
known_pairs = set()
for r in kg.relations:
    known_pairs.add((r.source, r.target))

truly_novel = [(h.cause, h.effect) for h in all_novel
               if (h.cause, h.effect) not in known_pairs]
novel_names = set()

# Generate report
lines = []
lines.append("# AGI Novel Discoveries Report\n")
lines.append(f"## Knowledge Base\n")
lines.append(f"- PubMed abstracts ingested: ~11,000")
lines.append(f"- Concepts in KnowledgeGraph: {kg.total_ingested}")
lines.append(f"- Causal relations extracted: {kg.total_relations}")
lines.append(f"- Inference cycles run: ~{len(all_novel):,}")
lines.append(f"\n## Novelty Summary\n")
lines.append(f"| Metric | Value |")
lines.append(f"|--------|-------|")
lines.append(f"| Original relations | {kg.total_relations} |")
lines.append(f"| **Novel hypotheses generated** | **{len(all_novel):,}** |")
lines.append(f"| Novelty ratio (novel/original) | {len(all_novel)/max(1,kg.total_relations):.1f}x |")

by_type = {}
for h in all_novel:
    by_type.setdefault(h.inference_type, []).append(h)

lines.append(f"\n## By Inference Type\n")
for itype, hyps in sorted(by_type.items()):
    lines.append(f"### {itype.upper()} ({len(hyps):,})\n")
    for h in hyps[:10]:
        # Determine the key entities
        cause_clean = h.cause[:50].strip()
        effect_clean = h.effect[:50].strip()
        stars = "★" * max(1, int(h.confidence * 5))
        lines.append(f"- {stars} **{cause_clean}** → **{effect_clean}** (conf={h.confidence:.2f})")
        for ev in h.evidence_chain[:2]:
            lines.append(f"  - ↳ {ev[:70]}")
    if len(hyps) > 10:
        lines.append(f"  - *... and {len(hyps)-10} more*")

# Novel discoveries for major diseases
diseases = ["Alzheimer", "Parkinson", "Huntington", "ALS", "cancer", "diabetes", "stroke"]
lines.append(f"\n## Cross-Domain Transfers for Major Diseases\n")
for disease in diseases:
    disease_hyps = [h for h in by_type.get("transfer", [])
                    if disease.lower() in h.cause.lower() or disease.lower() in h.effect.lower()]
    if disease_hyps:
        lines.append(f"### {disease} ({len(disease_hyps)} novel transfers)\n")
        for h in disease_hyps[:5]:
            lines.append(f"- **{h.cause[:40]}** → **{h.effect[:40]}**")
            lines.append(f"  - Domain: {h.domain}, Confidence: {h.confidence:.2f}")
            for ev in h.evidence_chain[:2]:
                lines.append(f"  - {ev[:60]}")

# Abductive discoveries
abduced = by_type.get("abduction", [])
if abduced:
    lines.append(f"\n## Abductive Discoveries (inferred causes)\n")
    for h in abduced[:10]:
        lines.append(f"- **{h.cause[:45]}** → **{h.effect[:45]}** (plausibility={h.confidence:.2f})")

lines.append(f"\n## Summary\n")
lines.append(f"- **Total novel hypotheses**: {len(all_novel):,}")
lines.append(f"- **Chain inferences**: {len(by_type.get('chain', [])):,}")
lines.append(f"- **Cross-domain transfers**: {len(by_type.get('transfer', [])):,}")
lines.append(f"- **Abductive inferences**: {len(by_type.get('abduction', [])):,}")
lines.append(f"- **Contrapositive inferences**: {len(by_type.get('contrapositive', [])):,}")
lines.append(f"\n---")
lines.append(f"*Generated by NovaMind AGI InferenceEngine*")

report = "\n".join(lines)
with open(REPORT_PATH, "w", encoding="utf-8") as f:
    f.write(report)

print(f"\n{report[:2000]}")
print(f"\n[... full report saved to {REPORT_PATH}]")
print(f"\nStats:")
for k, v in engine.get_stats().items():
    print(f"  {k}: {v}")
